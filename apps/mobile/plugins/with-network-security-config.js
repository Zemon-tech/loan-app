/**
 * Custom Expo config plugin (D-NETSEC).
 *
 * Belt-and-suspenders Android network hardening that `expo-build-properties` cannot express:
 *   1. Writes `res/xml/network_security_config.xml` with cleartext OFF and SYSTEM-ONLY trust
 *      anchors (no user-installed CAs trusted), covering API 24-27 as well as 28+.
 *   2. Points `android:networkSecurityConfig` at it on the <application>.
 *   3. Sets `android:allowBackup="false"` so tokens are excluded from Android auto-backup.
 *
 * Requires a development build + `npx expo prebuild` (not Expo Go). Never hand-edit android/.
 */
const {
  withAndroidManifest,
  withDangerousMod,
  AndroidConfig,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const NETWORK_SECURITY_CONFIG_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by ./plugins/with-network-security-config.js (D-NETSEC). Do not edit by hand. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

function withNetworkSecurityXmlFile(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const resXmlDir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app',
        'src',
        'main',
        'res',
        'xml',
      );
      fs.mkdirSync(resXmlDir, { recursive: true });
      fs.writeFileSync(
        path.join(resXmlDir, 'network_security_config.xml'),
        NETWORK_SECURITY_CONFIG_XML,
        'utf8',
      );
      return cfg;
    },
  ]);
}

function withNetworkSecurityManifest(config) {
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    app.$['android:allowBackup'] = 'false';
    return cfg;
  });
}

/** @type {import('@expo/config-plugins').ConfigPlugin} */
module.exports = function withNetworkSecurityConfig(config) {
  config = withNetworkSecurityXmlFile(config);
  config = withNetworkSecurityManifest(config);
  return config;
};
